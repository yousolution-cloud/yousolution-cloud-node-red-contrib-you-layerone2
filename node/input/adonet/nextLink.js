module.exports = function (RED) {
    function AdoNextLinkNode(config) {
      RED.nodes.createNode(this, config);
      const node = this;
  
      node.on('input', async (msg) => {
        let nextLink = msg["nextLink"];
        const info = msg.nextLinkInfo;

        if (nextLink && info && info.nodeType && !info.nodeType.startsWith('you-layerone2-adonet-')) {
          node.warn(`NextLink generated by ${info.nodeType} (${info.nodeId}): not an AdoNet link`);
        }

        if(nextLink) {
          const u = new URL(nextLink);
          msg.nextLink = u.search;
        }

        if (!nextLink) {
          node.send([null, msg]);
          return;
        }
  
        node.send([msg, null]);
      });
    }
    RED.nodes.registerType('you-layerone2-adonet-next-link', AdoNextLinkNode, {});
  };
  